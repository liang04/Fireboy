## 正例夹具允许出现的警告（显式白名单，按「夹具名 → 警告里必须出现的子串」）。
##
## 为什么必须有这个白名单：夹具地形是**最小骨架** —— 为了只考验一条规则，
## 出生点、出口、机关都挤在一起，于是「捷径体检」这类**面向真实关卡**的
## 规则必然误报（实测三个既有正例全中）。
## 但「一律忽略正例的警告」又会把真问题一起放走：
## 比如 door_lock_on_exit 护的就是一条警告规则，豁免一旦失效，
## 它正是以**警告**的形态暴露出来的。
## 所以这里只有两条路：未列出的警告 = 失败；列出的警告 = 已知且已授权。
##
## 注意一个反直觉的事实：这条捷径警告**恰恰证明了地面层是通的**。
## 如果它消失了，先别高兴 —— 更可能是地形被改到把出生点/出口隔开了，
## 而那种「隔开」会以【致命】的形态出现（已删除的 box_stand_solvable 就踩过
## 这个坑：水娃被关在平台上、水门又摆在平台上，于是「不用触发机关就能到出口」
## 和「走不到自己的出口」两个结论同时成立）。
POSITIVE_ALLOWED_WARNINGS = {
    "coop_hold_plate":      ("不用触发任何机关就能到出口",),
    "double_plate_solvable": ("不用触发任何机关就能到出口",),
    "box_drop_to_plate":    ("不用触发任何机关就能到出口",),
    "door_lock_on_exit":    ("不用触发任何机关就能到出口",),
}


def _warning_allowed(kind, msg):
    """这条警告是不是这个正例夹具**已知且授权**的。"""
    if "【警告】" not in msg:
        return True                      # 只对警告做白名单，其余交给致命判定
    needles = POSITIVE_ALLOWED_WARNINGS.get(kind, ())
    return any(n in msg for n in needles)


def selftest():
    print("=== 校验器自检（每个夹具都必须命中指定规则）===")
    ok = True
    for kind, (needle, level) in FIXTURE_EXPECT.items():
        errs = validate(_broken_fixture(kind), 0)
        tag = "【%s】" % level
        hit = [m for m in errs if needle in m and tag in m]
        if hit:
            print("  [OK]   %-24s -> %s" % (kind, hit[0].split("：", 1)[-1][:66]))
        else:
            got = " / ".join(m.split("：", 1)[-1][:40] for m in errs) or "什么都没报"
            print("  [FAIL] %-24s 期望含「%s」的%s，实际得到：%s"
                  % (kind, needle, level, got))
            ok = False

    for kind in POSITIVE_FIXTURES:
        errs = validate(_broken_fixture(kind), 0)
        fatal = [m for m in errs if "【致命】" in m]
        # 正例只要「不被判死」就算过关 —— 警告是可以通过的。
        # 我一度想在校验器层面要求「正例零警告」，但那是错的：
        # 夹具地形是**最小骨架**，为了只考验一条规则而刻意留空，
        # 于是「出生点就在出口旁边、机关形同虚设」这类警告必然出现
        # （实测：coop_hold_plate / double_plate_solvable / box_drop_to_plate
        #   三个既有正例全都会报这条捷径警告，而它们本来就该放行）。
        # 正确做法是把「警告必须已授权」写成**显式白名单**，
        # 而不是把所有警告一律当成失败 —— 见 POSITIVE_ALLOWED_WARNINGS。
        bad = [m for m in errs
               if "【致命】" in m
               or not _warning_allowed(kind, m)]
        if bad:
            print("  [FAIL] %-24s 本该能通关，却报出未授权问题：%s"
                  % (kind, bad[0].split("：", 1)[-1][:56]))
            ok = False
        else:
            print("  [OK]   %-24s 判定为可通关（正确放行）%s"
                  % (kind, ("，另有 %d 条已授权警告" % len(errs)) if errs else ""))

    print("自检%s" % ("通过" if ok else "失败"))
    return ok



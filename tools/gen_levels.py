# --------------------------------------------------------- 「踩箱子垫脚」夹具骨架
## 这两个夹具共享同一套地形（一个带井的平台），只在【箱子有没有掉进井里】上分叉。
##
## 地形的每一条都是被几何约束逼出来的，不是随手画的：
##   · 平台顶面 y=10、x=12..20，**脚下全填实**。这是本夹具最关键的一条：
##     从地面站立面 y=14 爬到平台站立面 y=10 要上升【4 行】——
##     远超跳跃上限 3.35 格，扩散模型和物理在这里**难得地一致**，
##     所以「必须垫一级」不是模型假象，是真实约束。
##     脚下若留空（浮空平台），玩家就能从下方绕进去，
##     「必须踩箱子」这个前提会凭空消失，夹具将以错误的理由变绿。
##   · 井口是平台**内部**掏空的一列（x=16，y=10..15）。

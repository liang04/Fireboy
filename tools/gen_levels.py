def immune_to(element, kind):
    if kind == "acid":
        return False
    if kind == "lava":
        return element == "fire"
    if kind == "water":
        return element == "water"
    return True


def channel_active(o, active):
    """机关是否已通电：channel 为空 = 一直工作；否则要看 channel 有没有被激活。"""
    ch = o.get("channel", "")
    return ch == "" or ch in active


def build_block_maps(grid, objects, element, active=frozenset()):
    """blocked[y][x]：该格对 element 不可进入（实心 / 会致死的液体 / 关着的门）
       virtual：移动平台两端提供的站立面（平台本身也可能受 channel 控制）
       fluid_surf：免疫液体的「液面」——免疫角色能浮在液面上走过去。
       deadly：会致死的液体格 —— 绝不能当落脚面。

    deadly 这一项看着多余（它本来就在 blocked 里），但缺了它会出大事：
    致命液体在物理上是触发区不是实体，角色踩上去是掉进去死，不是站住。
    如果只因为它「不可进入」就当成可站立的地面，校验器就会认为角色能
    从岩浆顶上走过去 —— 于是再宽的岩浆也拦不住人，元素门彻底失效。

    第三项是「元素门」这个设计手法的前提。角色免疫的液体对他不是障碍：
    他可以下到液里、浮起来、沿着液面一路走过去。如果只把液体当成
    「可以跳过去的空隙」，那 6 格宽的岩浆会变成谁都过不去 —— 可实际上
    火娃大可以趟过去，水娃不行。宽度差就是元素门：
      ≤4 格宽：两人都能过（一个趟水、一个跳过去）
      ≥6 格宽：只有免疫方能过，另一方被彻底分开
    """
    H, W = len(grid), len(grid[0])
    blocked = [[False] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            ch = grid[y][x]
            if ch in SOLID_CHARS:
                blocked[y][x] = True
            elif ch in FLUID_CHARS:
                blocked[y][x] = not immune_to(element, FLUID_CHARS[ch])

    # 关着的门是墙。门从 cell 所在格向下延伸 height 格。
    for o in objects:
        if o.get("type") != "door" or channel_active(o, active):
            continue
        cx, cy = o["cell"]
        h = int(o.get("height", 3))
        for r in range(cy, cy + h):
            if 0 <= r < H:
                blocked[r][cx] = True

    fluid_surf = set()
    deadly = set()
    for y in range(H):
        for x in range(W):
            ch = grid[y][x]
            if ch not in FLUID_CHARS:
                continue
            if not immune_to(element, FLUID_CHARS[ch]):
                deadly.add((x, y))
                continue
            # 液面 = 液体格，且正上方不是液体（头顶净空由落点检查负责）
            if y - 1 >= 0 and grid[y - 1][x] not in FLUID_CHARS:
                fluid_surf.add((x, y))

    virtual = set()
    for o in objects:
        if o.get("type") != "moving_platform" or not channel_active(o, active):
            continue
        fx, fy = o["from"]
        tx, ty = o["to"]
        w = int(o.get("width", 3))
        # 平台碰撞体只占格子上半部分，站立面就在格子的顶边
        for cx in range(fx, fx + w):
            virtual.add((cx, fy))
        for cx in range(tx, tx + w):
            virtual.add((cx, ty))
    return blocked, virtual, fluid_surf, deadly


def surfaces_at(col, blocked, virtual, fluid_surf=frozenset(),
                deadly=frozenset()):
    """某一列所有可站立的面（返回行号，数值越小越高）。
       免疫液体的液面也算落脚点 —— 角色会浮在液面上。
       会致死的液体不算 —— 踩上去是掉进去死，不是站住。"""
    out = []
    for y in range(len(blocked)):
        if (col, y) in deadly:
            continue
        here = blocked[y][col] or ((col, y) in virtual) or ((col, y) in fluid_surf)
        if not here:
            continue
        # 头顶净空：不能是实心，也不能是平台。
        # 注意这里【不能】排除「头顶是免疫液体」—— 站在池底时身体本来
        # 就浸在液体里，那正是合法状态，排掉它就无法下到池底捡宝石。
        above_free = (y - 1 >= 0) and (not blocked[y - 1][col]) \
            and ((col, y - 1) not in virtual)
        if above_free:
            out.append(y)
    return out


def platform_links(objects, active=frozenset()):
    """移动平台两端的连边：站上这一头就被带到另一头。"""
    links = []
    for o in objects:
        if o.get("type") != "moving_platform" or not channel_active(o, active):
            continue
        fx, fy = o["from"]
        tx, ty = o["to"]
        w = int(o.get("width", 3))
        a = [(cx, fy) for cx in range(fx, fx + w)]
        b = [(cx, ty) for cx in range(tx, tx + w)]
        for p in a:
            for q in b:
                links.append((p, q))
                links.append((q, p))
    return links


# ---------------------------------------------------------------- 谜题求解
def _solid_at(grid, c, y):
    return 0 <= y < len(grid) and 0 <= c < len(grid[0]) \
        and grid[y][c] in SOLID_CHARS


def _door_blocks(objects, c, y, active):
    for o in objects:
        if o.get("type") != "door" or channel_active(o, active):
            continue
        cx, cy = o["cell"]
        h = int(o.get("height", 3))
        if c == cx and cy <= y < cy + h:
            return True
    return False


def _exposed_surface(grid, objects, c, y, active):
    """(c, y) 是不是一个露天的落脚面：y 行实心，且 y-1 行没有实心方块或关着的门。"""
    if not _solid_at(grid, c, y):
        return False
    if y - 1 < 0:
        return False
    return not _solid_at(grid, c, y - 1) and not _door_blocks(objects, c, y - 1, active)


def box_drop_landing(grid, objects, push_x, push_s, active, max_drop=None):
    """木箱从 (push_x, push_s) 被推出去之后，沿重力落到哪里。

    返回 (落点列, 落点落脚行, 落差格数, 终止原因)，够不到地面时返回 None。
    终止原因：
      "ground"  落到实心格上（正常）
      "fluid"   落进液体（箱子会沉底，永久报废 —— 校验器判致命）
      "void"    一路掉到关卡底部都没接住（箱子永久丢失 —— 校验器判致命）
      "drift"   落点列越界（关卡边框，物理上到不了，静默丢弃不当错误）

    模型说明：横飘实测恒 0.42 格 → 取整为「落到正下方那一列」，
    所以落点列 = push_x（箱子被推离边缘后，就落在它自己那一列的下方）。
    """
    W = len(grid[0])
    H = len(grid)
    if not (0 <= push_x < W):
        return None
    if max_drop is None:
        max_drop = MAX_BOX_DROP_CELLS

    y = push_s
    while y < H:
        if _solid_at(grid, push_x, y):
            # 落点上方那一格如果是液体，实际是掉进液体里（箱子浮不上来）
            if y - 1 >= 0:
                ch = grid[y - 1][push_x] if push_x < len(grid[y - 1]) else "."
                if ch in FLUID_CHARS:
                    return (push_x, y - 1, (y - 1) - push_s, "fluid")
            return (push_x, y, y - push_s, "ground")
        if push_x < len(grid[y]):
            ch = grid[y][push_x]
            if ch in FLUID_CHARS:
                return (push_x, y, y - push_s, "fluid")
        y += 1
    return (push_x, H - 1, (H - 1) - push_s, "void")


def box_reachable(grid, objects, box_cell, player_reach, active):
    """木箱能被推到哪些位置，返回 {(列, 落脚行)}。

    规则来自 PushBox._detect_push()：
      · 玩家必须紧贴木箱（水平距离 ≤ 1.05 格）
      · 玩家与木箱的高度差 ≤ 0.9 格 —— 因为落脚面都是整格的，
        等价于「玩家站的那一格必须和木箱同一层」
      · 木箱只能沿同一高度的连续地面被推，推不上台阶

    2026-09-19 新增【重力投递】：木箱被推出高台边缘之后会沿重力下落，
    落到下方第一个落脚面。这是「把箱子交给另一个人」的唯一物理途径，
    所以落点在本题里必须被算作「可达」—— 否则任何跨层用箱的关卡
    都会被判成「门解不开」，而它其实完全可解。

    落体的边界由 max_drop / 落点性质决定，但**可达性**只看「能不能到」：
    落进液体或掉出关卡底部的落点，对「箱子到达」而言是假答案，
    这里直接**不加入** seen（由 validate() 再单独判致命/警告，见 box_drop_* 规则）。
    """
    W = len(grid[0])
    # MovingPlatform carries PushBox through the same rider detector as players.
    # Model endpoint decks and a swept-clear transport edge, never teleport boxes.
    decks = set()
    carries = {}
    for platform in objects:
        if platform.get("type") != "moving_platform" or not channel_active(platform, active):
            continue
        ax, ay = platform["from"]; bx, by = platform["to"]
        width = int(platform.get("width", 3))
        for offset in range(width):
            aa, bb = (ax + offset, ay), (bx + offset, by)
            decks.update((aa, bb))
            steps = max(abs(bx - ax), abs(by - ay), 1)
            clear = all(not _solid_at(grid, round(aa[0] + (bb[0] - aa[0]) * i / steps),
                                      round(aa[1] + (bb[1] - aa[1]) * i / steps) - 1)
                        and not _door_blocks(objects, round(aa[0] + (bb[0] - aa[0]) * i / steps),
                                             round(aa[1] + (bb[1] - aa[1]) * i / steps) - 1, active)
                        for i in range(steps + 1))
            if clear:
                carries.setdefault(aa, set()).add(bb)
                carries.setdefault(bb, set()).add(aa)
    def exposed(c, row):
        return _exposed_surface(grid, objects, c, row, active) or (
            (c, row) in decks and not _solid_at(grid, c, row - 1)
            and not _door_blocks(objects, c, row - 1, active))
    c0 = box_cell[0]
    # 木箱受重力，落在它下方第一个实心格上
    s0 = None
    for y in range(box_cell[1], len(grid)):
        if _solid_at(grid, c0, y):
            s0 = y
            break
    if s0 is None:
        return set()

    seen = {(c0, s0)}
    q = deque([(c0, s0)])
    while q:
        c, s = q.popleft()
        for endpoint in carries.get((c, s), ()):
            if endpoint not in seen:
                seen.add(endpoint)
                q.append(endpoint)
        for dc in (-1, 1):
            nc = c + dc
            if not (0 <= nc < W):
                continue
            # 目标列必须在同一高度有落脚面，且头顶净空
            if exposed(nc, s):
                behind = c - dc
                if not (0 <= behind < W):
                    continue
                if not exposed(behind, s):
                    continue
                if (behind, s) not in player_reach:
                    continue
                if (nc, s) not in seen:
                    seen.add((nc, s))
                    q.append((nc, s))
                continue
            # --- 边缘外没有同高落脚面：尝试「推出边缘 → 重力投递」
            behind = c - dc
            if not (0 <= behind < W):
                continue
            if not exposed(behind, s):
                continue
            if (behind, s) not in player_reach:
                continue
            land = box_drop_landing(grid, objects, nc, s, active)
            if land is None:
                continue
            land_x, land_y, drop, why = land
            if why in ("void", "fluid"):
                continue                  # 假答案，不进可达集
            if (land_x, land_y) in seen:
                continue
            seen.add((land_x, land_y))
            q.append((land_x, land_y))
    return seen



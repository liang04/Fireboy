def double_plate_solvable(grid, objects, cells, fire, water, active):
    """双钥匙板整组能否被【同时】压住。

    为什么必须是「同时」：一块板按顺序踩两次不算 —— 那两个人各走一趟就行了，
    就又退化成普通压力板，「必须同时在场」这个新决策消失。
    所以两块板必须由**不同的压住者**承担：两人各一块，或一人一箱。

    模型边界（和 solve_endgame 同源）：假设两人行动互不阻塞，
    于是「两人的可达集里各有一块板」就等价于「他们能同时站上去」。
    它覆盖不了「必须掐着秒同时按下」这类要求 —— 那只能靠真人试玩。
    """
    if len(cells) < 2:
        return False
    targets = []
    for c in cells:
        # 站立面在板所在格的下一行，与 PressurePlate 的约定一致
        targets.append((int(c[0]), int(c[1]) + 1))

    boxes = [o for o in objects if o.get("type") == "box"]
    options = []
    for t in targets:
        opts = set()
        if t in fire:
            opts.add("fire")
        if t in water:
            opts.add("water")
        for bi, b in enumerate(boxes):
            if t in box_reachable(grid, objects, b["cell"], fire | water, active):
                opts.add("box%d" % bi)
        options.append(opts)

    from itertools import product
    for combo in product(*options):
        if any(not c for c in combo):
            continue
        # 同一个人/同一个箱子不可能同时压两块板
        if len(set(combo)) != len(combo):
            continue
        return True
    return False


def plate_surfaces(plate):
    """Supported floor cells covered by a one-cell or wide receiving plate."""
    x, y = plate["cell"]
    return {(x + dx, y + 1) for dx in range(max(int(plate.get("width", 1)), 1))}


def solve_channels(grid, objects):
    """求「哪些 channel 最终能被激活」，返回 (active, 未解开的依赖列表)。

    思路是不动点迭代 —— 不断问「现在能到的地方里，有没有新的开关可以打开」：
      · 杠杆：够得着就能拉，且自锁 → 永久激活
      · 压力板 + 木箱：箱子推上去就一直压着 → 永久激活
      · 压力板 + 人站：只能临时生效（站着的人去不了出口），
        所以只当作「探路的踏脚石」：如果它让另一个人够到了新杠杆，
        那根杠杆就是永久解
    迭代到不再增长为止。这样「门的开关在门后面」这类循环依赖会被自然识别为无解。
    """
    active = set()
    unsolved = []
    for _ in range(24):
        fire = compute_reach(grid, objects, "fire", active)
        water = compute_reach(grid, objects, "water", active)
        grew = False

        # --- 杠杆：够得着就永久激活
        for o in objects:
            if o.get("type") != "lever" or o.get("channel") in active:
                continue
            cx, cy = o["cell"]
            if (cx, cy + 1) in fire or (cx, cy + 1) in water:
                active.add(o["channel"])
                grew = True

        # --- 双钥匙板：整组【同时】被压住一次就永久激活（自锁）
        #     自锁是关键：如果只是「按住才开」，两人都被钉在板上，谁也走不了 ——
        #     那就是循环依赖。永久激活之后两人才能都离开、都走那扇门。
        for o in objects:
            if o.get("type") != "double_plate" or o.get("channel") in active:
                continue
            if double_plate_solvable(grid, objects, o.get("cells", []),
                                     fire, water, active):
                active.add(o["channel"])
                grew = True

        # --- 压力板 + 木箱：推上去就永久压住
        for o in objects:
            if o.get("type") != "plate" or o.get("channel") in active:
                continue
            px, py = o["cell"]
            targets = plate_surfaces(o)
            both = fire | water
            for b in objects:
                if b.get("type") != "box":
                    continue
                if targets & box_reachable(grid, objects, b["cell"], both, active):
                    active.add(o["channel"])
                    grew = True
                    break

        # --- 压力板 + 人站着：只是踏脚石，看它能不能换来一根杠杆
        for o in objects:
            if o.get("type") != "plate" or o.get("channel") in active:
                continue
            px, py = o["cell"]
            for pinner, explorer in (("fire", "water"), ("water", "fire")):
                held = fire if pinner == "fire" else water
                if not (plate_surfaces(o) & held):
                    continue
                tmp = active | {o["channel"]}
                after = compute_reach(grid, objects, explorer, tmp)
                before = fire if explorer == "fire" else water
                # A held gate can let the explorer deliver a box back onto a plate.
                # The keeper's reachable set must not act as a second courier.
                for box in (b for b in objects if b.get("type") == "box"):
                    delivered = box_reachable(grid, objects, box["cell"], after, tmp)
                    for plate in (p for p in objects if p.get("type") == "plate"):
                        if plate_surfaces(plate) & delivered and plate["channel"] not in active:
                            active.add(plate["channel"])
                            grew = True
                for l in objects:
                    if l.get("type") != "lever" or l.get("channel") in active:
                        continue
                    lx, ly = l["cell"]
                    if (lx, ly + 1) in after and (lx, ly + 1) not in before:
                        active.add(l["channel"])
                        grew = True

        if not grew:
            break

    # 报告没被解开的门
    for o in objects:
        if o.get("type") == "door" and not channel_active(o, active):
            unsolved.append(o.get("channel"))
    return active, unsolved


def compute_reach(grid, objects, element, active):
    """在给定已激活 channel 的前提下，算出 element 能站到哪些地方。

    ⚠️ 2026-09-19：这里原先有个 `with_boxes` 参数，用于把「踩木箱垫脚」
    算成一种移动手段。该模型已整体移除 —— 完整理由见本文件上方那段
    【已删除】注释（结论：垫脚在本作不可能构成必要条件，且通不过
    「新玩家决策」这条红线）。调用点也已全部改回本签名。
    """
    blocked, virtual, fluid_surf, deadly = build_block_maps(
        grid, objects, element, active)
    links = platform_links(objects, active) + portal_links(objects)
    marker = "F" if element == "fire" else "W"
    for y, line in enumerate(grid):
        x = line.find(marker)
        if x >= 0:
            return reachable(blocked, virtual, links, (x, y + 1),
                             fluid_surf, deadly)
    return set()

    links = platform_links(objects, active) + portal_links(objects)
    marker = "F" if element == "fire" else "W"
    for y, line in enumerate(grid):
        x = line.find(marker)
        if x >= 0:
            return reachable(blocked, virtual, links, (x, y + 1),
                             fluid_surf, deadly)
    return set()


def portal_links(objects):
    """传送门：同 pair_id 的两端互相连通，站进去就被送到另一头的脚下。"""
    by_pair = {}
    for o in objects:
        if o.get("type") != "portal":
            continue
        cx, cy = o["cell"]
        by_pair.setdefault(o.get("pair", ""), []).append((cx, cy + 1))
    links = []
    for cells in by_pair.values():
        for i in range(len(cells)):
            for j in range(i + 1, len(cells)):
                links.append((cells[i], cells[j]))
                links.append((cells[j], cells[i]))
    return links


def _in_shaft(blocked, virtual, x, y):
    """(x, y) 是不是一个【竖井】里的站立面。

    判据（对应 smoke.gd _probe_shaft_climb 的试验装置）：
      · 脚下 (x, y+1) 实心（有底）
      · 左右两侧在**同一深度段**内都是实心（或越界）—— 也就是被夹住
      · 夹住它的那两堵壁**往上延伸至少 2 格**（否则只是站在一个矮凹槽里，
        一抬腿就出去了，不算井）

    为什么要单独识别它：扩散模型只比较相邻格高度差，一格宽的竖直通道里
    每对相邻格都差 1 格 ⇒ 模型认为「一步步往上走」合法 ⇒ 判人能从任意深
    的井里爬出来。**实测这是假的**（宽 1 格的井净爬升 0.00 格）。
    """
    H, W = len(blocked), len(blocked[0])
    if not (0 <= y < H and 0 <= x < W):
        return False

    def wall(cx):
        return not (0 <= cx < W) or blocked[y][cx] or ((cx, y) in virtual)

    if not (wall(x - 1) and wall(x + 1)):
        return False

    # 壁必须「高」到构成井：往上看 2 行，两侧仍然是实心
    for dy in (1, 2):
        yy = y - dy
        if yy < 0:
            continue
        def wall_at(cx):
            return not (0 <= cx < W) or blocked[yy][cx] or ((cx, yy) in virtual)
        if not (wall_at(x - 1) and wall_at(x + 1)):
            return False
    return True


def shaft_width(blocked, virtual, x, y):
    """(x,y) 所在竖井的宽度（格）。左右连续实心壁之间的空腔宽度。"""
    H, W = len(blocked), len(blocked[0])
    left = x
    while left - 1 >= 0 and not (blocked[y][left - 1] or ((left - 1, y) in virtual)):
        left -= 1
    right = x
    while right + 1 < W and not (blocked[y][right + 1] or ((right + 1, y) in virtual)):
        right += 1
    return right - left + 1


def _can_move(blocked, virtual, x, y, nx, ny, d):
    """从站立面 (x,y) 到 (nx,ny) 是否可行。"""
    H, W = len(blocked), len(blocked[0])
    rise = y - ny                     # 正数 = 要往上爬

    # 落点头顶必须有 1 格净空（角色高 28px，占 1 格）
    if ny - 1 < 0 or blocked[ny - 1][nx] or ((nx, ny - 1) in virtual):
        return False

    # ── 竖井修正（2026-09-19）──────────────────────────────────────────
    # 井里的可用跳跃上限**不是** MAX_JUMP_UP_CELLS(3)，而是实测的
    # MAX_SHAFT_CLIMB_CELLS(2)；宽 1 格的井更是只有 0 格。
    # 不修正就会放行「人能从 6 格深的井里自由爬出」这类关卡 ——
    # 第 10 关就靠这一条活着，见 MEMORY.md 与 smoke.gd _probe_shaft_climb。
    if rise > 0:
        if _in_shaft(blocked, virtual, x, y):
            w = shaft_width(blocked, virtual, x, y)
            limit = 0 if w <= 1 else MAX_SHAFT_CLIMB_CELLS
            if rise > limit:
                return False

    if d == 1:
        if rise > MAX_STEP_UP_CELLS:
            return False
        if rise < 0:                  # 往下跳：中间不能卡住
            for r in range(y, ny):
                if 0 <= r < H and (blocked[r][nx] or ((nx, r) in virtual)):
                    return False
        return True

    # 跨沟：上升不能超过跳跃高度（井里已按竖井上限卡过）
    if rise > MAX_JUMP_UP_CELLS:
        return False
    # A descending jump cannot land under a solid shelf by falling through it.
    # Check the destination-column descent as well as the launch arc below.
    if rise < 0:
        for row in range(y - 1, ny):
            if 0 <= row < H and blocked[row][nx]:
                return False

    # 跳跃弧线经过的头顶几格必须净空（注意不含起跳行本身 —— 那正是要跨过去的坑）
    lo, hi = (x, nx) if x < nx else (nx, x)
    for cx in range(lo + 1, hi):
        for r in range(y - 1, y - 2 - MAX_JUMP_UP_CELLS, -1):
            if 0 <= r < H and (blocked[r][cx] or ((cx, r) in virtual)):
                return False
    return True


def reachable(blocked, virtual, links, start, fluid_surf=frozenset(),
                deadly=frozenset()):
    """BFS：按实测运动能力扩散，返回可达站立面的集合。"""
    W = len(blocked[0])
    seen = set()
    q = deque()
    if start is None:
        return seen
    seen.add(start)
    q.append(start)
    while q:
        x, y = q.popleft()
        for a, b in links:
            if a == (x, y) and b not in seen:
                seen.add(b)
                q.append(b)
        for d in range(1, MAX_GAP_CELLS + 1):
            for nx in (x - d, x + d):
                if not (0 <= nx < W):
                    continue
                for ny in surfaces_at(nx, blocked, virtual, fluid_surf, deadly):
                    if (nx, ny) in seen:
                        continue
                    if not _can_move(blocked, virtual, x, y, nx, ny, d):
                        continue
                    seen.add((nx, ny))
                    q.append((nx, ny))
    return seen


def solve_endgame(grid, objects, base_active, exits):
    """求一种「谁按住哪块压力板」的分配，让两人都能到各自出口。

    为什么需要这一步：门不一定能被永久打开。经典解法是
    「一人站板、一人过门」，过门的人再拉一根自锁杠杆，把最后那扇门永久
    打开 —— 这时站板的人才能离开。所以终局判定必须允许「临时按住」的 channel，
    否则这类关卡会被误判成无解。

    模型：枚举每块压力板的归属（没人 / 火娃 / 水娃），然后
      火娃可达集 = base_active ∪ {水娃按住的板} 下算
      水娃可达集 = base_active ∪ {火娃按住的板} 下算
    再要求每块被按住的板，按住它的人确实够得着。

    边界：这个模型假设「两人行动互不阻塞、且只需一次交接」。
    它覆盖不了「两人必须同时各按一块板第三扇门才开」这类设计 —— 那种关卡
    校验器会放行，得人工试玩确认。
    """
    from itertools import product

    plates = [o for o in objects if o.get("type") == "plate"]
    boxes = [o for o in objects if o.get("type") == "box"]
    if len(plates) > 6:
        # 3^6=729 种分配还能秒算，再多就是关卡设计失控了
        return None, "压力板多达 %d 块，终局求解规模爆炸" % len(plates)

    best = None
    for assign in product((None, "fire", "water"), repeat=len(plates)):
        held = {"fire": set(), "water": set()}
        for p, who in zip(plates, assign):
            if who is not None:
                held[who].add(p.get("channel"))

        # 火娃享受水娃按住的板，反之亦然
        reach_f = compute_reach(grid, objects, "fire",
                                base_active | held["water"])
        reach_w = compute_reach(grid, objects, "water",
                                base_active | held["fire"])

        ok = True
        for p, who in zip(plates, assign):
            if who is None:
                continue
            px, py = p["cell"]
            r = reach_f if who == "fire" else reach_w
            if not (plate_surfaces(p) & r):
                ok = False
                break
        if not ok:
            continue

        for element, marker in (("fire", "E"), ("water", "Q")):
            ex = exits[element]
            if ex is None:
                ok = False
                break
            r = reach_f if element == "fire" else reach_w
            if (ex[0], ex[1] + 1) not in r:
                ok = False
                break
        if not ok:
            continue

        # 优先选「需要按住的板最少」的分配 —— 那是最不容易玩崩的解法
        cost = sum(1 for a in assign if a is not None)
        if best is None or cost < best[0]:
            best = (cost, dict(held), reach_f, reach_w)

    if best is None:
        return None, None
    return best, None


def _can_self_destruct(deadly, reach_set, grid):
    """从已有可达集里，玩家能不能主动送死（走进/跳进自己元素的致命液体）而重生。

    判据：存在某个落脚面 (c, r)（人站在 (c, r-1)），它的近旁
    —— 同一行的左右各一格、以及脚下一行与上一行的左右各一格
    （人一步跨/一跳够得着的范围）—— 里有该元素的致命液体。

    ⚠️ 「脚下一行」这一条不能省（实测第 3 关就是靠它翻案的）：
      火娃站在右段地面 (26,20)，水潭在 (25,21) —— 潭面比他矮一格。
      他往左走一步就踏空掉进潭里淹死，是货真价实的自杀手段；
      但只看同一行的话 (25,20) 是空的，规则会误判成「够不到液体」。

    为什么死区体检需要它：本作允许「掉进陷阱 = 死一次 = 从出生点重来」，
    所以**够得到液体**的封闭区域不是死局，只有**够不到**的才是。
    """
    if not deadly:
        return False
    W = len(grid[0])
    H = len(grid)
    for (c, r) in reach_set:
        sy = r - 1                          # 人所在的那一格
        for yy in (sy - 1, sy, sy + 1):
            if not (0 <= yy < H):
                continue
            for cx in (c - 1, c, c + 1):
                if 0 <= cx < W and (cx, yy) in deadly:
                    return True
    return False


def validate(lv, index):
    """返回问题列表（空 = 完全通过）。"""
    errs = []
    grid, objects = lv["grid"], lv["objects"]
    from enrichment.prototype_validator import project
    objects, projection_errors, temporal = project(grid, objects)
    errs.extend(projection_errors)
    if temporal:
        print("      （动态机关：静态仅检查可达上界；时序与互斥由引擎测试和真实按键回放验证）")
    H, W = len(grid), len(grid[0])
    tag = "关卡%d" % (index + 1)

    for i, line in enumerate(grid):
        if len(line) != W:
            errs.append("%s: 第 %d 行宽度 %d != %d" % (tag, i, len(line), W))

    for ch, label in (("F", "火娃出生点"), ("W", "水娃出生点"),
                      ("E", "火门"), ("Q", "水门")):
        n = sum(line.count(ch) for line in grid)
        if n != 1:
            errs.append("%s: %s 出现 %d 次（应为 1 次）" % (tag, label, n))

    for plate in (o for o in objects if o.get("type") == "plate"):
        width = int(plate.get("width", 1))
        x, y = plate["cell"]
        if width < 1 or x < 0 or x + width > W or y < 0 or y >= H:
            errs.append("%s: 【致命】压力板宽度或位置越界" % tag)

    def find(ch):
        for y, line in enumerate(grid):
            x = line.find(ch)
            if x >= 0:
                return (x, y)
        return None

    spawns = {"fire": find("F"), "water": find("W")}
    exits = {"fire": find("E"), "water": find("Q")}

    def display(p):
        """把内部坐标 (列, 站立行) 还原成作者在网格里**看到**的行号。

        内部约定是「网格行 == 站立行」（角色站在 (x,y) 这一格的顶面），
        出生点标记在 y-1 行；出口标记则在 y 行本身。
        报错时说「(12,13)」而作者在网格第 14 行看到那个 F，是上一轮
        排查时真实出现的困惑来源 —— 所以这里显式换算回去。
        """
        if p is None:
            return "?"
        return "(x=%d, 网格第%d行)" % (p[0], p[1] + 1)

    # 先解机关链：只有真正能被打开的门才算通路
    # 先解机关链，找出「永久打不开」的门
    active, unsolved = solve_channels(grid, objects)

    # 终局：允许「一人按住压力板，另一人借机过门」。找不到任何一种
    # 板分配能让两人都到出口，才是真的不可通关。
    # 注意：即使终局不成立也不能提前 return —— 后面的池深、宝石检查
    # 必须照样跑完。否则会出现「关卡因为别的原因挂了，池深超标反而被漏掉」。
    plan, note = solve_endgame(grid, objects, active, exits)
    # Sequential keeper exchanges need actor positions retained across gate closes.
    # This is a bounded checkpoint-state search, not an allowlist or error suppression.
    if plan is None:
        from enrichment.relay_validator import solve as solve_relay
        relay = solve_relay(grid, objects, globals())
        if relay is not None:
            active, plan = relay["active"], relay["plan"]
            note = None
            print("      （连续接力状态搜索通过：%d 个状态）" % relay["states"])

    if note:
        errs.append("%s: 【致命】%s" % (tag, note))
        plan = None
    if plan is None:
        # 只有终局也走不通时，未解开的门才算致命。
        # 「门解不开」本身不是死罪 —— 一人按板、另一人借机通过照样能通关，
        # 而那种情形机关链求解器是看不出来的，得靠终局求解放行。
        for ch in unsolved:
            errs.append("%s: 【致命】channel '%s' 的门解不开 —— "
                        "触发它的开关要么够不着，要么在门后面（循环依赖）"
                        % (tag, ch))
        for element, marker in (("fire", "火娃"), ("water", "水娃")):
            ex = exits[element]
            if ex is None:
                continue
            seen = compute_reach(grid, objects, element, active)
            if (ex[0], ex[1] + 1) not in seen:
                errs.append("%s: 【致命】%s 走不到自己的出口 (%d,%d)，"
                            "本关无法通关" % (tag, marker, ex[0], ex[1]))
        # 退化：终局不成立时，仍用「没人按板」的可达集跑完剩余检查
        plan = (0, {"fire": set(), "water": set()},
                compute_reach(grid, objects, "fire", active),
                compute_reach(grid, objects, "water", active))

    _cost, held, reach_f, reach_w = plan
    if _cost and (held["fire"] or held["water"]):
        who = []
        if held["fire"]:
            who.append("火娃按住 %s" % "/".join(sorted(held["fire"])))
        if held["water"]:
            who.append("水娃按住 %s" % "/".join(sorted(held["water"])))
        if who:
            print("      （通关需要 %s）" % "，".join(who))

    # 捷径体检：如果什么都不做也能到出口，说明机关链被地形绕过了。
    # 校验器只回答「能不能到」，不回答「是不是按设计的路到」——
    # 这条规则是给后者兜底的最低限度保险：至少能抓出「整条链被跳过」。
    # 它抓不出「跳过一半」，那种仍要靠人工试玩。
    # 只查有门的关卡 —— 教学关本来就没有机关链可绕。
    has_mech = any(o.get("type") in ("door", "lever", "plate", "double_plate")
                   for o in objects)
    if has_mech and not any("走不到自己的出口" in m for m in errs):
        bare = {"fire": compute_reach(grid, objects, "fire", frozenset()),
                "water": compute_reach(grid, objects, "water", frozenset())}
        for element, mark in (("fire", "火娃"), ("water", "水娃")):
            ex = exits[element]
            if ex is None:
                continue
            if (ex[0], ex[1] + 1) in bare[element]:
                errs.append("%s: 【警告】%s 不用触发任何机关就能到出口 —— "
                            "存在绕过整条机关链的捷径" % (tag, mark))

    # 死区体检（2026-09-26 新增）：找「掉进去就出不来」的空腔。
    #
    # 为什么必须单独有这条：**出口可达 ≠ 关卡可玩**。第 10 关 v2 曾有一个
    # 致命形态 —— 写「井壁」的那句 `g.rect(2, 13, 6, 18, " ")` 其实是**空操作**
    # （Grid 默认填充本来就是 "."），于是 y=13~18 整层是空的：不是一口井，
    # 是一块横跨全关的空腔。玩家从上层地面掉进去以后：
    #     ① 到不了出口（出口在上层，rise 远超跳跃上限 3 格）
    #     ② 回不到出生点   ③ 也自杀不了（那一关一滴液体都没有）
    #   ⇒ 这一局永久报废，只能重开。而**上面所有的规则都放行了它** ——
    #   出口确实可达。这是「从出生点出发能不能到出口」这类规则的结构性盲区。
    #
    # 判据：p 是死区点，当且仅当从出生点可达，且从 p 出发
    #   ① 到不了自己的出口  ② 回不到出生点  ③ 够不到任何致命液体送死
    #
    # 两条边界（都会误报，实测踩过）：
    #   · 移动平台的虚拟落脚面要排除：模型把「站上去就被带走」简化成一条
    #     固定连边，从平台中段出发回不到起点，但真人是能随时跳下来的。
    #   · **局部的井是合法设计**（第 10 关井底就是故意困人的）—— 所以只有
    #     死区**横向一直连到关卡边界**（碰到第 1 列或第 W-2 列）才判死：
    #     那种「一整条通铺」的空腔不可能是设计意图，只可能是少画了一层底。
    if not any("走不到自己的出口" in m for m in errs):
        for element, mark in (("fire", "火娃"), ("water", "水娃")):
            ex = exits[element]
            if ex is None:
                continue
            blocked, virtual, fluid_surf, deadly = build_block_maps(
                grid, objects, element, active)
            links = platform_links(objects, active) + portal_links(objects)
            start = None
            for y, line in enumerate(grid):
                x = line.find("F" if element == "fire" else "W")
                if x >= 0:
                    start = (x, y + 1)
                    break
            if start is None:
                continue
            reach = reachable(blocked, virtual, links, start,
                              fluid_surf, deadly)
            targets = {(ex[0], ex[1] + 1)}
            traps = []
            for p in sorted(reach):
                if p == start or p in virtual:
                    continue
                r2 = reachable(blocked, virtual, links, p, fluid_surf, deadly)
                if start in r2 or (r2 & targets):
                    continue
                if _can_self_destruct(deadly, r2, grid):
                    continue
                traps.append(p)
            edge = [p for p in traps if p[0] <= 1 or p[0] >= W - 2]
            if edge:
                cols = sorted(set(p[0] for p in traps))
                errs.append(
                    "%s: 【致命】%s 有一个横贯关卡的死区（列 %d~%d 掉下去就再也"
                    "回不来：到不了出口、也够不到任何液体自杀）—— "
                    "几乎肯定是地形少画了一层底"
                    % (tag, mark, cols[0], cols[-1]))

    for element in ("fire", "water"):
        held_by_partner = held["water"] if element == "fire" else held["fire"]
        blocked, _virtual, _fs, _deadly = build_block_maps(
            grid, objects, element, active | held_by_partner)

        sp = spawns[element]
        if sp is None:
            errs.append("%s: 缺少 %s 出生点" % (tag, element))
            continue
        # ⚠️ 内部约定：**网格行 == 站立行**。
        #    角色站在 (x,y) 这一格的【顶面】，所以 y 那一格本身必须是实心；
        #    网格里的 F/W 标记画在**正上方那一行**(y-1)，也就是「人所在的空格」。
        #    于是 (x, y) 这个坐标既表示「站立面」也表示「脚底下那一格」，
        #    两者是同一个格子 —— 校验器全程按这个约定工作（扩散模型、
        #    reachable 集合、宝石/出口的归属判定全都是站立面坐标）。
        #    ⚠️ 例外：box_reachable() 返回的 s 是箱子【坐着】的实心行，
        #    不是站立行（箱子自身占 s-1 格）—— 这个 off-by-one 曾让
        #    已删除的 box_stand 模型静默失效，引用它时务必先减 1。
        #    push_box.gd 里木箱落在 solid 行的上一行、玩家再踩上去，
        #    最终位置换算到这套坐标同样是 (x, solid_row) —— 三处自洽。
        start = (sp[0], sp[1] + 1)
        if start[1] >= H or not (blocked[start[1]][start[0]]):
            errs.append("%s: 【致命】%s 出生点 %s 脚下不是实地"
                        % (tag, element, display(sp)))
            continue

        seen = reach_f if element == "fire" else reach_w

        # 宝石按颜色归属：红宝石归火娃、蓝宝石归水娃
        for o in objects:
            if o.get("type") != "gem":
                continue
            cx, cy = o["cell"]
            owner = "fire" if o.get("color", "red") == "red" else "water"
            if owner != element:
                continue
            if not (0 <= cx < W and 0 <= cy < H):
                errs.append("%s: 宝石 (%d,%d) 越界" % (tag, cx, cy))
                continue
            if (cx, cy + 1) not in seen:
                errs.append("%s: 【警告】%s 色宝石 (%d,%d) 对 %s 不可达"
                            % (tag, o.get("color"), cx, cy, element))

        # 池深检查：免疫方掉进去必须还游得上来，否则软锁
        for y in range(H):
            for x in range(W):
                ch = grid[y][x]
                if ch not in FLUID_CHARS:
                    continue
                if not immune_to(element, FLUID_CHARS[ch]):
                    continue
                depth, yy = 0, y
                while yy + 1 < H and not blocked[yy + 1][x]:
                    yy += 1
                    depth += 1
                if depth > MAX_SWIM_UP_CELLS:
                    errs.append(
                        "%s: 【致命】(%d,%d) 的%s池深 %d 格，%s 掉进去游不上来"
                        "（上浮上限 %d 格）"
                        % (tag, x, y, FLUID_CHARS[ch], depth, element,
                           MAX_SWIM_UP_CELLS))

    # ---- 门顶太矮：熟练玩家能跳过门顶抄近路，而校验器的扩散模型看不出来。
    #      模型把 >MAX_STEP_UP_CELLS(2) 的台阶一律当墙，但物理跳高实测 3.35 格 ——
    #      也就是说 3 格高的门顶，模型说"过不去"、玩家说"我跳上去了"。
    #      而 §校验器能力边界 明确写了「跳过一半机关的捷径」是它抓不到的。
    #      判据：过门要把身体抬到门顶之上，需要上升 (落脚行 - 门顶行) 格，
    #      跳高上限 3.35 → 必须 ≥4 才安全。
    #      例外一：门顶正上方就是实体（例如第 4 关那扇 height=3 的门，
    #      上面正好被水娃的栈桥压住），那门虽矮也封得死，不报警。
    #      例外二（2026-09-19 补）：门被夹在【凹龛】里，左右两侧都是实体。
    #      这时「跳上门顶」根本没有落脚点 —— 门顶两侧是墙，跳上去也只是
    #      贴着墙，而且门顶上方通常就是凹龛顶。
    #      例外三（2026-09-19 补）：门【直接盖在出口格上】—— 它不是挡路的墙，
    #      而是锁在出口上的锁（第 10 关的两扇门都是这样）。这种门必须矮：
    #      它要覆盖的就是出口那一格，加高会盖住出口上方的空间、
    #      反而把出口埋掉。而且「跳过它」没有意义 —— 跳过一把锁不等于
    #      打开了它，出口照样进不去（出口判定看的是角色是否站在门格里）。
    #      判据：门的 cell 正好是某个出口格的坐标 → 这是把锁，不报警。
    exit_cells = set()
    for ch in ("E", "Q"):
        for y, line in enumerate(grid):
            x = line.find(ch)
            if x >= 0:
                exit_cells.add((x, y))
    for o in objects:
        if o.get("type") != "door":
            continue
        dx, dy = o["cell"]
        dh = int(o.get("height", 1))
        if not 0 <= dx < W:
            continue
        if _solid_at(grid, dx, dy - 1):
            continue                       # 门顶被实体封住，跳不过去
        if (dx, dy) in exit_cells:
            continue                       # 盖在出口上的「锁」，不是挡路的门
        # 凹龛豁免：门所在行的左右两侧都是实体 → 门被夹住，跳上门顶也无处可站
        if _solid_at(grid, dx - 1, dy) and _solid_at(grid, dx + 1, dy):
            continue
        floor_row = None
        for y in range(dy + dh - 1, H):    # 从门底往下找落脚面（含门底自己）
            if _solid_at(grid, dx, y):
                floor_row = y
                break
        if floor_row is None:
            continue
        rise = floor_row - dy
        if rise < 4:
            errs.append("%s: 【警告】门 (%d,%d) 门顶离落脚面只有 %d 格，"
                        "熟练玩家可能跳过门顶抄近路（跳高实测 3.35 格，需 ≥4 格）"
                        % (tag, dx, dy, rise))

    # ---- 双钥匙板：结构完整性 + 可达性。
    #      这个机关最阴的失败模式不是「门解不开」（solve_channels 会抓到），
    #      而是【两块板里只有一块够得到】—— 那样它看起来是个可解谜题，
    #      实际上永远差一个人，玩家会在那儿耗到放弃。
    for o in objects:
        if o.get("type") != "double_plate":
            continue
        cells = o.get("cells", [])
        if len(cells) < 2:
            errs.append("%s: 【致命】双钥匙板 channel '%s' 只有 %d 块板，"
                        "至少要 2 块（否则就是普通压力板）"
                        % (tag, o.get("channel"), len(cells)))
            continue
        reach_any = reach_f | reach_w
        unreachable = []
        for c in cells:
            cx, cy = int(c[0]), int(c[1])
            if not (0 <= cx < W and 0 <= cy < H):
                errs.append("%s: 【致命】双钥匙板 (%d,%d) 越界" % (tag, cx, cy))
                continue
            if (cx, cy + 1) not in reach_any:
                unreachable.append((cx, cy))
        if unreachable:
            errs.append("%s: 【致命】双钥匙板 channel '%s' 有 %d 块板谁都够不到：%s"
                        "—— 它是「永远差一个人」的谜题，不是难题"
                        % (tag, o.get("channel"), len(unreachable),
                           ", ".join("(%d,%d)" % c for c in unreachable)))

    # ---- 重力投递：木箱被推出边缘之后的落点必须「可用」。
    #      这是「把箱子交给另一个人」唯一的物理途径（液体对箱子是墙，
    #      台阶推不上去，传送门不载货），所以它的三种坏落法都得拦住：
    #        · 掉出关卡底部    → 致命（箱子是跨区唯一资源，丢了就是永久软锁）
    #        · 落进液体        → 致命（箱子沉底取不回，实测 lava/water 行为一致）
    #        · 落差超过上限    → 警告（落点还在，但推手看不清箱子落哪，
    #                            玩家无法规划下一步 —— 是认知负担不是软锁）
    #      注意这条规则**不能**把所有落差都判死：「有落差」正是这个机关的设计意图，
    #      正例夹具 box_drop_to_plate 就是靠它成立的。
    reach_any = reach_f | reach_w
    for o in objects:
        if o.get("type") != "box":
            continue
        bx, by = o["cell"]
        # 箱子当前所在层：往下找第一个落脚面
        cur = None
        for y in range(by, H):
            if _solid_at(grid, bx, y):
                cur = y
                break
        if cur is None:
            continue
        # 枚举所有「能把箱子推出边缘」的位置：箱子在这一层、推手站在背后
        for s in range(0, H):
            for edge_c in range(1, W - 1):
                if not _exposed_surface(grid, objects, edge_c, s, active):
                    continue
                for dc in (-1, 1):
                    behind = edge_c - dc
                    nc = edge_c + dc
                    if not (0 <= nc < W and 0 <= behind < W):
                        continue
                    if not _exposed_surface(grid, objects, behind, s, active):
                        continue
                    if (behind, s) not in reach_any:
                        continue
                    if (edge_c, s) != (bx, cur) and not (
                            (edge_c, s) in box_reachable(
                                grid, objects, o["cell"], reach_any, active)):
                        continue
                    # 目标格同高有落脚面 → 不是「推出边缘」，跳过
                    if _exposed_surface(grid, objects, nc, s, active):
                        continue
                    land = box_drop_landing(grid, objects, nc, s, active)
                    if land is None:
                        continue
                    lx, ly, drop, why = land
                    if why == "drift":
                        continue
                    # 「贴在边缘的池子」与「掉下悬崖」必须区分开 ——
                    # drop == 0 表示木箱是**平推**进同一层的液体里（池子与地面齐平），
                    # 那需要玩家主动多推一下，是他的失误不是关卡的结构缺陷，
                    # 重启一局即可（支柱 3「失误要便宜」）→ 只警告。
                    # drop > 0 才是「重力投递」特有的失败模式：箱子从高台掉下去，
                    # 掉到玩家可能够不到的地方 → 致命。
                    same_level = (drop == 0)
                    if why == "void":
                        lvl = "警告" if same_level else "致命"
                        errs.append(
                            "%s: 【%s】木箱 (%d,%d) 从 (%d,%d) 被推出边缘后会"
                            "一路掉出关卡底部 —— 箱子是跨区唯一资源，"
                            "丢下去就再也拿不回来"
                            % (tag, lvl, bx, by, edge_c, s))
                    elif why == "fluid":
                        if same_level:
                            errs.append(
                                "%s: 【警告】木箱 (%d,%d) 从 (%d,%d) 平推进"
                                "(%d,%d) 的液体池（同高）—— 虽说玩家不多推一下就没事，"
                                "但箱子和池子齐平等于把「毁掉资源」做成了顺手动作"
                                % (tag, bx, by, edge_c, s, lx, ly))
                        else:
                            errs.append(
                                "%s: 【致命】木箱 (%d,%d) 从 (%d,%d) 被推出后会落进"
                                "(%d,%d) 的液体里 —— 箱子会沉底取不回（永久软锁）。"
                                "液体对人是半透膜、对箱子是全墙，"
                                "两者不能放在同一落点列"
                                % (tag, bx, by, edge_c, s, lx, ly))
                    elif drop > MAX_BOX_DROP_CELLS:
                        errs.append(
                            "%s: 【警告】木箱 (%d,%d) 从 (%d,%d) 被推出后落差 %d 格，"
                            "超过上限 %d —— 推手看不清落点，玩家无法规划下一步"
                            % (tag, bx, by, edge_c, s, drop, MAX_BOX_DROP_CELLS))
    return errs


# ============================================================ 自检
## 校验器最大的风险不是报错太多，而是「永远通过」——那就等于没有。
## 这里用几个故意做坏的关卡反向验证：每一个都必须被抓出来。
def _broken_fixture(kind):
    """返回一个有特定缺陷的关卡，用于验证校验器确实能发现问题。"""
    # --- 三个「重力投递」夹具 + 一个「竖井」夹具自带独立地形。
    #     为什么不让它们共用基础网格：投递必须让推手爬得上高台，
    #     而基础网格的出生点/出口/台阶会跟高台打架（实测把 E/Q/F/W 都盖掉了）。
    #     夹具的目的是「只考验一条规则」，地形越干净越好。
    if kind in ("box_no_landing", "box_drop_to_plate", "box_drop_too_far",
                "box_drop_into_hazard", "shaft_escapes"):
        return _box_drop_fixture(kind)
    if kind == "trap_region":
        # 死区体检的夹具：右侧地面整条开口，下面是 4 格深的空腔
        # （站立面行 12 − 地面行 7 = rise 5 > 跳跃上限 3 ⇒ 爬不回去），
        # 而这一关【一滴液体都没有】⇒ 掉下去也死不了。
        # 空腔一路通到右边界（列 28 == W-2）⇒ 命中「横贯关卡」判据。
        # 出口和两个出生点都摆在左边安全区，所以「走不到出口」不会报 ——
        # 这正是要证明的：出口可达的关卡照样可能是死局。
        gt = Grid(30, 14)
        gt.border()
        gt.row(12, 1, 28, "#")           # 空腔底（站立面行 12）
        gt.row(7, 1, 8, "#")             # 左段地面（实心行 7，人站在行 6）
        gt.rect(1, 8, 8, 11, "#")        # 左段地下填实 —— 空腔只剩列 9~28
        gt.put(3, 6, "F")
        gt.put(5, 6, "W")
        gt.put(6, 6, "E")                # 出口都在左段地面（脚下 (6,7) 实心）
        gt.put(8, 6, "Q")                # 出口都在左段地面（脚下 (8,7) 实心）
        return {"name": "fixture:" + kind, "subtitle": "",
                "grid": gt.rows(), "objects": []}
    g = Grid(30, 16)
    g.border()
    g.row(14, 1, 28, "#")            # 地面（站立面）
    g.row(15, 1, 28, "#")
    g.put(3, 13, "F")
    g.put(6, 13, "W")
    g.put(26, 12, "E")               # 出口在台阶上
    g.put(20, 13, "Q")               # 出口在地面
    g.row(13, 24, 28, "#")           # 台阶：第 13 行
    objs = []
    if kind == "gap_too_wide":
        g.row(14, 10, 22, ".")       # 挖一条 13 格的沟，远超跳跃极限
    elif kind == "step_too_high":
        g.row(13, 8, 9, "#")
        g.row(12, 8, 9, "#")
        g.row(11, 8, 9, "#")
        g.row(10, 8, 9, "#")         # 4 格高墙，跳不上去
    elif kind == "door_circular":
        # 门的压力板被放在门后面 —— 循环依赖，永远打不开
        g.put(12, 13, "#")
        objs = [{"type": "plate", "cell": [20, 13], "channel": "A"},
                {"type": "door", "cell": [12, 7], "height": 7, "channel": "A"},
                {"type": "box", "cell": [5, 13]}]
    elif kind == "box_cannot_reach_plate":
        # 木箱和压板之间隔着一格台阶，箱子推不过去
        g.row(13, 12, 12, "#")
        objs = [{"type": "plate", "cell": [16, 13], "channel": "A"},
                {"type": "door", "cell": [12, 7], "height": 7, "channel": "A"},
                {"type": "box", "cell": [8, 13]}]
    elif kind == "pool_too_deep":
        g.row(14, 10, 12, "~")       # 1 格深的水潭

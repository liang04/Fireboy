def par_for(level_no):
    """保留的暂定真人难度目标，沿用历史普通最快/估值 × PAR_FACTOR。

    十关已用真实输入验证全宝石且限时达标，详情见 full_gem_routes_round2.md。
    自动回放只证明当前门槛可达；真人合作的难度平衡仍待实际试玩标定。
    数值未变，因此本轮不提升 RATING_VERSION。
    """
    return round(BASE_TIMES[level_no] * PAR_FACTOR, 1)


# ---------------------------------------------------------------- 网格 DSL
class Grid:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.g = [["." for _ in range(w)] for _ in range(h)]

    def rect(self, x0, y0, x1, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.g[y][x] = ch

    def row(self, y, x0, x1, ch):
        self.rect(x0, y, x1, y, ch)

    def put(self, x, y, ch):
        self.g[y][x] = ch

    def border(self, ch="#"):
        for y in range(self.h):
            self.g[y][0] = ch
            self.g[y][self.w - 1] = ch

    def rows(self):
        return ["".join(r) for r in self.g]



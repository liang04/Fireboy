##     中间那 4 行落差反而消失，「垫脚」这件事不再必要。
##     井底落在 y=15（关卡底部地板行），再往下箱子会掉出关卡。
##   · 正例里箱子落井底（站立面 y=15，比井底地面高 1 格），
##     反例里箱子停在同列的地面上（站立面 y=14，差 4 行）。
##     **一格之差，解法存在与否完全不同** —— 这就是要用两个夹具夹住的边界。
##   · 火门只有 1 格高：这又是刀锋区（3 格会被跳过）—— 但它被夹在
##     平台实体之间，左右都是实体，走「凹龛豁免」那条路。
##     夹具必须自己不触发 low_door 警告，否则它会因为「另一个原因」变红。
##   · 火门由水娃的拉杆开 —— 没有循环依赖，也保证「门解不开」不会先于
##     本夹具要考验的那条规则触发。
##
## 【已删除】_box_stand_fixture()（2026-09-19）
##   它原本要夹住「有箱子 vs 没箱子」这个边界，但**两个分支的输出完全相同**
##   （均 gain=0），即它从来没有真正咬住过任何东西 —— 违反「给校验器加规则
##   必须同时加夹具」的精神（夹具存在，但它证明不了规则会咬人）。

def emit_level(fn_name, lv):
    out = ["static func %s() -> Dictionary:\n\treturn {\n" % fn_name]
    out.append('\t\t"name": "%s",\n' % lv["name"])
    out.append('\t\t"subtitle": "%s",\n' % lv["subtitle"])
    out.append('\t\t"par_time": %s,\n' % lv.get("par_time", 0.0))
    # 内容修订号必须一起输出：游戏靠它判断存档里该关的旧成绩还成不成立。
    out.append('\t\t"revision": %d,\n' % int(lv.get("revision", 1)))
    if "camera_margin" in lv:
        out.append('\t\t"camera_margin": %s,\n' % lv["camera_margin"])
    out.append('\t\t"grid": [\n')
    for r in lv["grid"]:
        out.append('\t\t\t"%s",\n' % r)
    out.append("\t\t],\n")
    out.append('\t\t"objects": [\n')
    for o in lv["objects"]:
        block = gd_value(o, 4).replace("\n", "\n\t\t\t")
        out.append("\t\t\t%s,\n" % block)
    out.append("\t\t],\n")
    out.append("\t}\n")
    return "".join(out)


def main():
    out_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "scripts", "levels", "levels.gd")

    # 先跑自检：如果坏关卡都抓不出来，后面「校验通过」这四个字毫无意义
    if not selftest():
        print("\n校验器自身不可信，已中止生成。")
        sys.exit(1)
    print()

    all_errs = []
    for i, lv in enumerate(LEVELS):
        e = validate(lv, i)
        # 三星门槛是关卡数据的一部分：缺了不会崩，但星级会静默退化成「全宝石即三星」，
        # 这种「不说话的功能缺失」必须由生成器喊出来 —— 见 docs/DESIGN.md 星级一节。
        if float(lv.get("par_time", 0.0)) <= 0.0:
            e.append("【警告】缺少 par_time：三星会退化成「全宝石即三星」，不再考核速度")
        all_errs.extend(e)
        # 基准是外推值的关必须标出来，否则它会安静地混进「实测」里 ——
        # 这正是上一轮「作者更快了却没人回去重算」的成因。
        est = "  新回放校准的暂定真人目标" if (i + 1) in ENRICHED_LEVELS else ("  ⚠ 基准为估值" if (i + 1) in BASE_TIMES_ESTIMATED else "")
        print("%-14s %dx%d  对象 %2d 个  三星≤%2.0fs  %s%s"
              % (lv["name"], len(lv["grid"][0]), len(lv["grid"]),
                 len(lv["objects"]), float(lv.get("par_time", 0.0)),
                 "校验通过" if not e else "%d 个问题" % len(e), est))
        for m in e:
            print("   - " + m)

    if any("【致命】" in m for m in all_errs):
        print("\n存在致命问题，已中止生成。")
        sys.exit(1)

    names = ", ".join("_level_%02d()" % (i + 1) for i in range(len(LEVELS)))
    body = HEADER % names
    body += "\n\n".join(
        emit_level("_level_%02d" % (i + 1), lv) for i, lv in enumerate(LEVELS))

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("\n已生成 %s（%d 关，%d 字节）" % (out_path, len(LEVELS), len(body)))
    warns = [m for m in all_errs if "【警告】" in m]
    if warns:
        print("注意：有 %d 条警告（不阻断生成）" % len(warns))


if __name__ == "__main__":
    main()

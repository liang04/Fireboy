# -*- coding: utf-8 -*-
"""
关卡 10「投递」地形 —— v5（方案 A：箱子与受益人同分区）

v4 被推翻的原因（见 docs/mechanic_gravity_drop.md §6.4）：
  液体对【人】是半透膜，对【箱子】是完全不可通行的墙 ——
  箱子只能沿同高地面被推，而液体不是它的可站立面（实测会沉底）。
  所以「用液体分区 + 用箱子做跨区资源」两者互斥。

方案 A：放弃跨区，箱子与受益人（火娃）同在左区。
  张力从「谁得到箱子」变成「**什么时候推下去**」——
  因为推下去之后箱子就回不来了，而井底有火门。

设计意图（一句话）：
  **箱子推下去就回不来 —— 两人得先确认井下真的安全。**

分区（全部用非液体手段）：
  · 左区（列 1~13）：火娃 + 木箱 + 竖井（火门在井里）
  · 右区（列 14~30）：水娃 + 她的出口
  · 两区用一个【高度差 4 格】的台阶墙分开
    —— 4 格 > 跳跃上限 3 → 谁都过不去；但这不是最终形态，
       最终要靠机关（双钥匙板 / 杠杆）打开

  但等一下 —— 如果两人被墙隔开且都过不去，那他们无法合作。
  所以正确的做法是：**两人能互相看见、能各自行动，但各有一处只有
  用箱子才能到达的地方**。也就是不硬隔离，用「高度」做局部难题。
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from gen_levels import Grid, compute_reach
from solve_box_placements import report_level

W, H = 34, 20

# ---- 关键坐标（改地形时只改这里）
JING_L, JING_R = 2, 6          # 竖井的列范围
JING_TOP = 12                  # 井口所在行（站立面 y=12）
JING_FLOOR = 19                # 井底（站立面）

FIRE_DOOR = (4, 15)            # 火门（井壁凹龛），站立面 (4,16)
WATER_DOOR = (31, 15)          # 水门（右区地面）
BOX_START = (10, 11)           # 木箱初始位置（左区地面）


def build():
    g = Grid(W, H)
    g.border()

    # ---------------------------------------------------- 地面
    g.row(H - 1, 1, W - 2, "#")            # 底层实心（站立面 y=19）

    # ---------------------------------------------------- 左区地面（站立面 y=12）
    g.row(12, 1, 13, "#")
    g.row(12, JING_L, JING_R, ".")         # 井口开口

    # 竖井：列 2~6，从 y=13 挖到 y=18（井底 y=19 保留）
    g.rect(JING_L, 13, JING_R, 18, " ")

    # 火门凹龛：井壁上挖一格
    g.put(FIRE_DOOR[0], FIRE_DOOR[1], "E")
    g.put(FIRE_DOOR[0], FIRE_DOOR[1] + 1, " ")

    # ---------------------------------------------------- 中间：4 格高的台阶墙
    # 这两条竖墙把左右区在【地面层】隔断，但上方是通的（可以绕）
    # → 不是硬隔离，只是让地面行走不能直穿
    g.rect(15, 8, 15, 11, "#")             # 一根柱子（站立面 y=12 上方的障碍）

    # ---------------------------------------------------- 右区地面（站立面 y=12）
    g.row(12, 16, W - 2, "#")

    # ---------------------------------------------------- 高处通路：连接左右
    # 一条 y=8 的高架桥，从列 14 到列 20 —— 两人都能从各自一侧上去
    g.row(8, 14, 20, "#")

    # 上桥的台阶（左侧）：从 y=12 地面爬 4 格到 y=8 桥面
    # ⚠️ 每级只能 2 格（MAX_STEP_UP_CELLS），所以要两级
    g.row(10, 11, 12, "#")                 # 站立面 y=10
    g.row( 9, 13, 14, "#")                 # 站立面 y=9
    # 右侧同理
    g.row(10, 19, 20, "#")
    g.row( 9, 21, 22, "#")

    # ---------------------------------------------------- 出生点与出口
    g.put(7, 11, "F")                      # 火娃在左区
    g.put(WATER_DOOR[0], WATER_DOOR[1], "Q")   # 水门在右区
    g.put(25, 11, "W")                     # 水娃在右区

    return g


def main():
    g = build()
    grid = g.rows()

    print("=" * 72)
    print("关卡 10「投递」v5 —— 方案 A：箱子与火娃同在左区")
    print("=" * 72)
    print("\n地形：")
    for i, line in enumerate(grid):
        print("  %2d %s" % (i, line))

    objs = [
        {"type": "box", "cell": [BOX_START[0], BOX_START[1]]},
    ]

    report_level(grid, "关卡10 v5", objects=objs)

    # ---- 捷径自检
    reach_fire = compute_reach(grid, objs, "fire", frozenset())
    exit_stand = (FIRE_DOOR[0], FIRE_DOOR[1] + 1)
    print("\n[捷径自检] 火娃不用箱子能否到达火门 %s？" % (exit_stand,))
    if exit_stand in reach_fire:
        print("  ⚠️ 能。箱子不是必需品 —— 火门要放得更难够到。")
    else:
        print("  ✅ 不能。箱子是必需品。")

    print("\n" + "=" * 72)
    print("过关判据（四条全绿才算收敛）")
    print("=" * 72)
    print("""  ① 有落点落在井里（列 2~6, y=19）
  ② 推手含 fire
  ③ 落差 <= 7 格
  ④ 捷径自检 ✅""")
    print("""
  注意：地形里的 4 格柱子是【测试残留】—— 它没参与玩法，v6 应该删掉或
        改成真正的机关（双钥匙板）。当前版本只为验证求解器的三道闸。""")


if __name__ == "__main__":
    main()
